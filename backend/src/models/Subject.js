const mongoose = require("mongoose");

// A topic lives inside its subject (embedded) because we always load them together.
const topicSchema = new mongoose.Schema({
  title: { type: String, required: true },
  summary: { type: String, required: true },
  keyPoints: { type: [String], default: [] },
  example: {
    language: { type: String, default: "" },
    code: { type: String, default: "" },
  },
  interviewQuestions: [
    {
      question: { type: String, required: true },
      answer: { type: String, required: true },
    },
  ],
  references: [
    {
      title: { type: String, required: true },
      url: { type: String, required: true },
    },
  ],
  deepDive: { type: String, default: "" },
});

const subjectSchema = new mongoose.Schema(
  {
    name: { type: String, required: true },
    slug: { type: String, required: true, unique: true },
    icon: { type: String, default: "📘" },
    color: { type: String, default: "#E8A33D" },
    description: { type: String, default: "" },
    topics: [topicSchema],
    isCustom: { type: Boolean, default: false }, // true = generated by AI when a user asked for it
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: "User", default: null },
  },
  { timestamps: true }
);

module.exports = mongoose.model("Subject", subjectSchema);
